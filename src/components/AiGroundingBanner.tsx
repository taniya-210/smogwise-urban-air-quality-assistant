import { Database, RefreshCw, Sparkles } from 'lucide-react';

interface AiGroundingBannerProps {
  generatedBy: 'gemini' | 'fallback';
  dataSourcesUsed?: string[];
  contextChanged?: boolean;
  contextChangedLabel?: string;
  onRegenerate?: () => void;
  regenerating?: boolean;
}

export function AiGroundingBanner({
  generatedBy,
  dataSourcesUsed,
  contextChanged = false,
  contextChangedLabel,
  onRegenerate,
  regenerating = false,
}: AiGroundingBannerProps) {
  const sources = dataSourcesUsed && dataSourcesUsed.length > 0 ? dataSourcesUsed : [];

  return (
    <div className="space-y-3">
      {contextChanged && onRegenerate && (
        <div
          role="status"
          className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 px-4 py-3 rounded-lg bg-blue-50 border border-blue-200 text-blue-950 text-xs"
        >
          <span>
            <span className="font-semibold">Inputs or location changed:</span>{' '}
            {contextChangedLabel ||
              'Your active city, air-quality reading, or preferences changed since this response was generated.'}
          </span>
          <button
            type="button"
            onClick={onRegenerate}
            disabled={regenerating}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-semibold text-white bg-blue-700 rounded-md hover:bg-blue-800 disabled:opacity-50 whitespace-nowrap shrink-0 self-start sm:self-center focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-blue-600"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${regenerating ? 'animate-spin' : ''}`} aria-hidden="true" />
            Regenerate Fresh Plan
          </button>
        </div>
      )}

      <div className="rounded-lg border border-slate-200 bg-slate-50/80 px-4 py-3 space-y-2">
        <div className="flex flex-wrap items-center justify-between gap-2 text-xs">
          <span
            className={`inline-flex items-center gap-1.5 font-semibold ${
              generatedBy === 'gemini' ? 'text-blue-800' : 'text-amber-900'
            }`}
          >
            <Sparkles className="w-3.5 h-3.5 shrink-0" aria-hidden="true" />
            {generatedBy === 'gemini'
              ? 'AI-Generated by Google Gemini'
              : 'AI FALLBACK MODE · DEMO / TEMPLATE GUIDANCE'}
          </span>
          <span className="text-[11px] text-slate-500">
            Measured/active data separated from generated recommendations
          </span>
        </div>

        {sources.length > 0 && (
          <div className="pt-2 border-t border-slate-200/80 space-y-1">
            <div className="flex items-center gap-1.5 text-[11px] font-semibold text-slate-600 uppercase tracking-wide">
              <Database className="w-3 h-3 text-slate-500 shrink-0" aria-hidden="true" />
              <span>Data Grounding Used</span>
            </div>
            <ul className="space-y-0.5 text-xs text-slate-600 list-disc pl-4">
              {sources.map((item, idx) => (
                <li key={idx} className="leading-relaxed break-words">
                  {item}
                </li>
              ))}
            </ul>
          </div>
        )}
      </div>
    </div>
  );
}
